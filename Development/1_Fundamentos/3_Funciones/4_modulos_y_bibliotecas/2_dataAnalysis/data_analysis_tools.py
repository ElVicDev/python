""" En este módulo, hemos definido una función llamada 
    calculate_mean que aprovecha la biblioteca NumPy (np) 
    para calcular la media de una lista de números. """

import pandas as pd
import numpy as np

def calculate_mean(data):
    """Calculates the mean of a list of numbers."""
    return np.mean(data)

